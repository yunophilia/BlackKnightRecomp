"""Writes runtime/game_addrs.inc: every address in tools/game_addrs.txt in each release.

  python tools/game_addrs.py

The USA addresses are written down; the others are found with tools/region_map.py
(function lists from out/<id>/functions.json, made by tools/build_generated.py). A
function must have the same code in the other release, and a patched or probed
instruction must be the same instruction, or the script stops. A release whose inputs
are not here keeps its column from the existing file.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import region_map                               # noqa: E402
from regions import REFERENCE, REGIONS, ROOT   # noqa: E402

SRC = os.path.join(ROOT, 'tools', 'game_addrs.txt')
OUT = os.path.join(ROOT, 'runtime', 'game_addrs.inc')
KINDS = {'func': 'FUNC', 'code': 'CODE', 'data': 'DATA'}


def read_list():
    rows = []
    for ln in open(SRC, encoding='utf-8'):
        ln = ln.split('#', 1)[0].strip()
        if not ln:
            continue
        parts = ln.split(None, 3)
        name, kind, addr = parts[0], parts[1], int(parts[2], 16)
        if kind not in KINDS:
            sys.exit(f'{name}: unknown kind {kind}')
        rows.append((name, kind, addr, parts[3] if len(parts) > 3 else ''))
    return rows


def load_inc():
    """runtime/game_addrs.inc as [(name, kind, {game ID: address})], in file order."""
    rows = []
    if os.path.exists(OUT):
        for m in re.finditer(r'GAME_ADDR\((\w+),\s*(\w+)((?:,\s*0x[0-9A-F]+)+)\)', open(OUT).read()):
            vals = [int(x, 16) for x in m.group(3).replace(',', ' ').split()]
            rows.append((m.group(1), m.group(2).lower(), {r.game_id: v for r, v in zip(REGIONS, vals)}))
    return rows


def read_previous():
    return {name: [cols[r.game_id] for r in REGIONS] for name, _, cols in load_inc()}


def same_insn(m, a, b):
    return region_map.norm(m.a.read32(a)) == region_map.norm(m.b.read32(b))


def map_region(m, rows):
    out, errors = {}, []
    for name, kind, addr, _ in rows:
        if kind == 'func':
            t = m.map_func(addr)
            if t is None:
                errors.append(f'{name}: function {addr:08X} has no counterpart')
            elif addr not in m.exact:
                errors.append(f'{name}: function {addr:08X} -> {t:08X} has different code')
        elif kind == 'code':
            t = m.map_code(addr)
            if t is None or not same_insn(m, addr, t):
                errors.append(f'{name}: instruction {addr:08X} has no counterpart')
        else:
            t = m.map_data(addr)
            if t is None:
                errors.append(f'{name}: {addr:08X} is not in a data section')
        out[name] = t
    return out, errors


def main():
    rows = read_list()
    prev = read_previous()
    cols = {REFERENCE.game_id: {name: addr for name, _, addr, _ in rows}}
    errors = []
    for i, r in enumerate(REGIONS[1:], start=1):
        if r.data_dir() and REFERENCE.data_dir() and os.path.exists(r.out('functions.json')):
            print(f'{r.game_id}: mapping {len(rows)} addresses', flush=True)
            cols[r.game_id], err = map_region(region_map.load(r), rows)
            errors += [f'{r.game_id} {e}' for e in err]
        else:
            print(f'{r.game_id}: inputs not here, keeping the previous addresses')
            missing = [name for name, *_ in rows if name not in prev]
            if missing:
                errors.append(f'{r.game_id}: no previous address for {", ".join(missing)}')
            cols[r.game_id] = {name: prev.get(name, [0] * len(REGIONS))[i] for name, *_ in rows}
    if errors:
        sys.exit('\n'.join(errors))

    w = max(len(n) for n, *_ in rows)
    lines = [
        '// Generated by tools/game_addrs.py from tools/game_addrs.txt: the game addresses the',
        '// runtime and the recompiler use, one column per release. Do not edit.',
        '//',
        f'//        {"name,".ljust(w + 1)} kind, ' + ' '.join((r.game_id + ',').ljust(11) for r in REGIONS).rstrip(' ,'),
    ]
    for name, kind, _, desc in rows:
        vals = ', '.join(f'0x{cols[r.game_id][name]:08X}' for r in REGIONS)
        lines.append(f'GAME_ADDR({(name + ",").ljust(w + 1)} {KINDS[kind]}, {vals})' + (f'   // {desc}' if desc else ''))
    text = '\n'.join(lines) + '\n'
    old = open(OUT, newline='\n').read() if os.path.exists(OUT) else None
    if old != text:
        with open(OUT, 'w', newline='\n') as fp:
            fp.write(text)
        print(f'wrote {OUT}')
    else:
        print('runtime/game_addrs.inc is up to date')


if __name__ == '__main__':
    main()
