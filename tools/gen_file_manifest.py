"""Writes runtime/install/files_<game id>.inc: path, size and SHA-1 of every installed file
of one release (sys/, files/, ticket/tmd/cert/h3), for the launcher's integrity checks.

  python tools/gen_file_manifest.py [game/extracted/DATA]

Run it on a known-good install of each release (the installer's output and DolphinTool's
"extract -g" are byte-identical); the release is read from sys/boot.bin. Contains hashes
only, no game data.
"""
import hashlib, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'game', 'extracted', 'DATA')
game_id = open(os.path.join(data, 'sys', 'boot.bin'), 'rb').read(6).decode('ascii')
rows = []
for d, _, fs in os.walk(data):
    for f in fs:
        p = os.path.join(d, f)
        rel = os.path.relpath(p, data).replace('\\', '/')
        if rel.startswith('disc/'):
            continue   # written by the installer only, not part of a DolphinTool extraction
        h = hashlib.sha1()
        with open(p, 'rb') as fp:
            for chunk in iter(lambda: fp.read(1 << 20), b''):
                h.update(chunk)
        rows.append((rel, os.path.getsize(p), h.hexdigest()))
rows.sort()
out = os.path.join(ROOT, 'runtime', 'install', f'files_{game_id.lower()}.inc')
with open(out, 'w', newline='\n') as fp:
    fp.write(f'// Generated by tools/gen_file_manifest.py: installed {game_id} files (path, size, SHA-1)\n')
    for rel, size, sha in rows:
        fp.write(f'{{ "{rel}", {size}ull, "{sha}" }},\n')
print(len(rows), 'files ->', out)
